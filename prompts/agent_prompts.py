def format_loan_card(record: dict) -> str:
    return (
        f"לקוח: {record.get('client_name')} ({record.get('client_id')})\n"
        f"סכום מבוקש: ₪{record.get('requested_amount'):,}\n"
        f"מטרה: {record.get('purpose')}\n"
        f"סטטוס: {record.get('status')}\n"
        f"הכנסה חודשית: ₪{record.get('monthly_income'):,}\n"
        f"דירוג אשראי: {record.get('credit_score')}\n"
        f"עיר: {record.get('city')}"
    ).replace(",", ",")
